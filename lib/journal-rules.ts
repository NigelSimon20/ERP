import { Prisma, PrismaClient } from '@prisma/client'
import { z } from 'zod'
import { journalEntrySchema } from './validators'
import { ApiError } from './api-error'
import { money, sumMoney, type MoneyInput } from './money'

type Db = PrismaClient | Prisma.TransactionClient

export interface JournalLineInput {
  accountId: string
  debit?: MoneyInput
  credit?: MoneyInput
  description?: string | null
}

export interface JournalLine {
  accountId: string
  debit: Prisma.Decimal
  credit: Prisma.Decimal
  description: string
}

// P1-6 (BUG-029): the rules every journal must satisfy, whether typed in by a
// user or generated by an invoice, receipt or payroll run. Returns problems
// rather than throwing so the Zod schema can report them per field.
export function journalLineProblems(lines: JournalLineInput[]): { path: (string | number)[]; message: string }[] {
  const problems: { path: (string | number)[]; message: string }[] = []
  if (lines.length < 2) problems.push({ path: ['lines'], message: 'A journal needs at least 2 lines' })
  lines.forEach((l, i) => {
    const d = money(l.debit)
    const c = money(l.credit)
    if (d.isNegative() || c.isNegative()) problems.push({ path: ['lines', i], message: 'Amounts cannot be negative' })
    else if (d.isZero() === c.isZero()) problems.push({ path: ['lines', i], message: 'Each line needs either a debit or a credit, not both and not neither' })
  })
  const totalDebit = sumMoney(lines.map((l) => l.debit))
  const totalCredit = sumMoney(lines.map((l) => l.credit))
  if (totalDebit.isZero() && totalCredit.isZero()) problems.push({ path: ['lines'], message: 'A journal total must be greater than zero' })
  else if (!totalDebit.eq(totalCredit)) {
    problems.push({ path: ['lines'], message: `Total debits (${totalDebit.toFixed(2)}) must equal total credits (${totalCredit.toFixed(2)})` })
  }
  return problems
}

export function normaliseJournalLines(lines: JournalLineInput[]): JournalLine[] {
  const problems = journalLineProblems(lines)
  if (problems.length) throw new ApiError(problems[0].message, 400, 'INVALID_JOURNAL')
  return lines.map((l) => ({ accountId: l.accountId, debit: money(l.debit), credit: money(l.credit), description: l.description ?? '' }))
}

// Every account must exist, belong to this company and be active.
export async function assertAccountsUsable(db: Db, companyId: string, accountIds: string[]) {
  const ids = Array.from(new Set(accountIds))
  const found = await db.chartOfAccount.findMany({
    where: { id: { in: ids }, companyId },
    select: { id: true, is_active: true, account_code: true },
  })
  const byId = new Map(found.map((a) => [a.id, a]))
  const missing = ids.filter((id) => !byId.has(id))
  if (missing.length) throw new ApiError('One or more accounts do not exist in this company', 400, 'INVALID_ACCOUNT')
  const inactive = found.filter((a) => a.is_active === false)
  if (inactive.length) {
    throw new ApiError(`Account ${inactive.map((a) => a.account_code ?? a.id).join(', ')} is inactive`, 400, 'INACTIVE_ACCOUNT')
  }
}

// BUG-016: "JE-auto-INV-" + "INV-000035" gave JE-auto-INV-INV-000035, and
// numbers that already carried a doubled prefix nested further.
export function autoJournalReference(kind: string, documentNumber: string): string {
  const prefix = `${kind}-`
  let n = documentNumber.replace(/^JE-auto-/, '')
  while (n.startsWith(prefix)) n = n.slice(prefix.length)
  return `JE-auto-${prefix}${n}`
}

// Code ranges by type (BUG-016: "4000 Bank Loan" was a liability in the
// revenue range). 5xxx and above are expenses.
const CODE_RANGES: Record<string, [number, number]> = {
  ASSET: [1000, 1999], LIABILITY: [2000, 2999], EQUITY: [3000, 3999], REVENUE: [4000, 4999], EXPENSE: [5000, 9999],
}
export function accountCodeProblem(code: string | null | undefined, type: string | null | undefined): string | null {
  if (!code || !type || !CODE_RANGES[type]) return null
  const n = Number(code.replace(/\D.*$/, ''))
  if (!Number.isFinite(n)) return null
  const [lo, hi] = CODE_RANGES[type]
  return n >= lo && n <= hi ? null : `${type} accounts use codes ${lo}–${hi}; ${code} is outside that range`
}

// Server-side journal schema (kept out of lib/validators, which the browser
// imports, because these rules need Prisma's Decimal).
export const journalEntryCreateSchema = journalEntrySchema.superRefine((data, ctx) => {
  for (const p of journalLineProblems(data.lines)) ctx.addIssue({ code: z.ZodIssueCode.custom, path: p.path, message: p.message })
})
